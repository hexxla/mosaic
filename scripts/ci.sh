#!/usr/bin/env bash
# Local and GitHub CI entry point.
set -euo pipefail
cd "$(dirname "$0")/.."

go mod tidy -diff
scripts/tool.sh actionlint .github/workflows/*.yml
scripts/tool.sh golangci-lint run ./...
go test -count=1 -race -timeout=10m ./...
go build ./cmd/...
scripts/tool.sh govulncheck ./...
